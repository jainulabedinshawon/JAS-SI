-- Give audit events a database-generated monotonic identifier.
-- Existing event IDs are preserved; the next generated ID starts above MAX(event_id).
ALTER TABLE public.jas_si_audit_events
    ALTER COLUMN event_id ADD GENERATED BY DEFAULT AS IDENTITY;

SELECT setval(
    pg_get_serial_sequence('public.jas_si_audit_events', 'event_id'),
    COALESCE((SELECT MAX(event_id) FROM public.jas_si_audit_events), 0) + 1,
    FALSE
);

-- Both the runtime audit writer and operator provisioner append audit events.
DO $$
DECLARE
    audit_event_id_sequence TEXT;
BEGIN
    audit_event_id_sequence :=
        pg_get_serial_sequence('public.jas_si_audit_events', 'event_id');

    IF audit_event_id_sequence IS NULL THEN
        RAISE EXCEPTION 'Audit event identity sequence was not created';
    END IF;

    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'jas_si_runtime') THEN
        EXECUTE format(
            'GRANT USAGE, SELECT ON SEQUENCE %s TO jas_si_runtime',
            audit_event_id_sequence
        );
    END IF;

    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'jas_si_provisioner') THEN
        EXECUTE format(
            'GRANT USAGE, SELECT ON SEQUENCE %s TO jas_si_provisioner',
            audit_event_id_sequence
        );
    END IF;
END
$$;
